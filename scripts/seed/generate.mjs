// Generates supabase/migrations/0004_seed_foods.sql and 0005_seed_prices.sql
// from scripts/seed/foods.mjs. Run: node scripts/seed/generate.mjs
import { writeFileSync } from "node:fs";
import { FOODS, SOURCE, PRICE_SOURCE } from "./foods.mjs";

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;
export const normalize = (s) =>
  s.toLowerCase().replace(/\([^)]*\)/g, " ").replace(/[^a-z0-9]+/g, " ").trim();

const rows = FOODS.map(
  ([name, aliases, cat, diet, allergens, qty, unit, unitGrams, kcal, p, c, f, fib, micros, raw]) =>
    `(${q(name)}, ${q(normalize(name))}, ${arr(aliases.map(normalize))}, ${q(cat)}, ${q(diet)}, ${arr(allergens)}, ` +
    `${qty}, ${q(unit)}, ${json(unitGrams)}, ${kcal}, ${p}, ${c}, ${f}, ${fib}, ${json(micros)}, ${raw ?? "null"}, ${q(SOURCE)})`,
);

writeFileSync(
  new URL("../../supabase/migrations/0004_seed_foods.sql", import.meta.url),
  `-- GENERATED by scripts/seed/generate.mjs. Edit scripts/seed/foods.mjs instead.
-- ${FOODS.length} common Indian foods. Values are approximate estimates, not lab data.
insert into public.food_database
  (food_name, normalized_name, aliases, category, dietary_type, allergens, serving_quantity, serving_unit,
   unit_grams, calories_kcal, protein_g, carbs_g, fat_g, fiber_g, micronutrients, raw_grams_per_serving, source)
values
${rows.join(",\n")}
on conflict (normalized_name) do update set
  food_name = excluded.food_name, aliases = excluded.aliases, category = excluded.category,
  dietary_type = excluded.dietary_type, allergens = excluded.allergens,
  serving_quantity = excluded.serving_quantity, serving_unit = excluded.serving_unit,
  unit_grams = excluded.unit_grams, calories_kcal = excluded.calories_kcal,
  protein_g = excluded.protein_g, carbs_g = excluded.carbs_g, fat_g = excluded.fat_g,
  fiber_g = excluded.fiber_g, micronutrients = excluded.micronutrients,
  raw_grams_per_serving = excluded.raw_grams_per_serving, source = excluded.source, updated_at = now();
`,
);

const priced = FOODS.filter((r) => r[15] != null);
const prices = priced.map(
  (r) => `(${q(normalize(r[0]))}, ${r[15]})`,
);
writeFileSync(
  new URL("../../supabase/migrations/0005_seed_prices.sql", import.meta.url),
  `-- GENERATED by scripts/seed/generate.mjs. Rough default prices (INR per kg or litre, as purchased).
-- Prices vary by city, season and shop: add rows for your own region or edit these.
insert into public.food_price_estimates (food_database_id, region, price_per_kg_or_litre, currency, source)
select f.id, 'default', v.price, 'INR', ${q(PRICE_SOURCE)}
from (values
${prices.join(",\n")}
) as v(normalized_name, price)
join public.food_database f on f.normalized_name = v.normalized_name
on conflict (food_database_id, region) do update
  set price_per_kg_or_litre = excluded.price_per_kg_or_litre, source = excluded.source, observed_at = now();
`,
);
console.log(`foods: ${FOODS.length}, priced: ${priced.length}`);
